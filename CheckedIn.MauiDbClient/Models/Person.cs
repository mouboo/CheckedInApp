using Microsoft.EntityFrameworkCore;
using System.ComponentModel.DataAnnotations;
using System.ComponentModel.DataAnnotations.Schema;

namespace CheckedIn.MauiDbClient;

// Data annotation corresponding to the SQL table
[Table("Person")]
[Index(nameof(Email), IsUnique = true)]
public class Person
{
    [Key] // Sets Primary Key
    [DatabaseGenerated(DatabaseGeneratedOption.Identity)] // Autogenerated unique ID
    [Column("PersonId")]
    public int PersonId { get; set;}

    [Required]
    [Column("FirstName")]
    [MaxLength(100)]
    public required string FirstName { get; set; } // Compiler ensures value is set to create a person

    [Required]
    [Column("LastName")]
    [MaxLength(100)]
    public required string LastName { get; set;}

    [Required]
    [Column("Phone")]
    [MaxLength(50)]
    
    public required string Phone { get; set;}

    [Required]
    [Column("Email")]
    [MaxLength(100)]
    public required string Email { get; set;}


}
